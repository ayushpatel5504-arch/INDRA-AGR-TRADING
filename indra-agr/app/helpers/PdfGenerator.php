<?php
declare(strict_types=1);

namespace App\Helpers;

use Dompdf\Dompdf;
use Dompdf\Options;

final class PdfGenerator
{
    public static function generateApplicationPdf(array $appData, string $outputPath): string
    {
        $options = new Options();
        $options->set('isRemoteEnabled', false);
        $options->set('defaultFont', 'DejaVu Sans');

        $dompdf = new Dompdf($options);
        $e = static fn(mixed $v): string => htmlspecialchars((string) ($v ?? '—'), ENT_QUOTES, 'UTF-8');

        $feeRow = '';
        if (!empty($appData['receipt_number'])) {
            $amtInr = number_format(((int) ($appData['fee_amount_paise'] ?? 0)) / 100, 2);
            $feeRow = "<tr><th>Payment Receipt No.</th><td>{$e($appData['receipt_number'])}</td><th>Fee Paid</th><td>INR {$amtInr} ({$e($appData['payment_status'] ?? 'SUCCESS')})</td></tr>";
        }

        $html = <<<HTML
<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<style>
  @page { margin: 24mm 18mm 22mm 18mm; }
  body { font-family: 'DejaVu Sans', sans-serif; color: #1B2B22; font-size: 11px; line-height: 1.5; }
  .header { border-bottom: 2px solid #174D32; padding-bottom: 10px; margin-bottom: 16px; }
  .company { font-size: 18px; font-weight: bold; color: #174D32; letter-spacing: 0.5px; }
  .tagline { font-size: 10px; color: #6B7280; margin-top: 2px; }
  .meta-bar { background: #F6F4EC; border: 1px solid #D9D4C5; padding: 8px 12px; margin-bottom: 16px; }
  .section-title { font-size: 12px; font-weight: bold; color: #174D32; border-bottom: 1px solid #C7A65A; padding-bottom: 4px; margin: 14px 0 8px; }
  table { width: 100%; border-collapse: collapse; margin-bottom: 10px; }
  td, th { border: 1px solid #E2DED2; padding: 6px 8px; text-align: left; vertical-align: top; }
  th { background: #F6F4EC; font-weight: bold; width: 28%; color: #103B27; }
  .notice { margin-top: 16px; padding: 8px 10px; background: #F6F4EC; border: 1px solid #C7A65A; font-size: 10px; }
  .footer { position: fixed; bottom: -14mm; left: 0; right: 0; font-size: 9px; color: #6B7280; border-top: 1px solid #E2DED2; padding-top: 4px; }
</style>
</head>
<body>
  <div class="header">
    <div class="company">INDRA AGR TRADING PVT. LTD.</div>
    <div class="tagline">Connecting Farmers, Growing Businesses. | Quality · Trust · Growth</div>
  </div>
  <div class="meta-bar">
    <strong>Application Number:</strong> {$e($appData['application_number'])} &nbsp;|&nbsp;
    <strong>Position:</strong> {$e($appData['job_title'])} &nbsp;|&nbsp;
    <strong>Status:</strong> {$e($appData['status'])} &nbsp;|&nbsp;
    <strong>Submitted:</strong> {$e($appData['submitted_at'])} IST
  </div>
  <div class="section-title">1. Personal & Contact Details</div>
  <table>
    <tr><th>Full Name</th><td>{$e($appData['full_name'])}</td><th>Father's Name</th><td>{$e($appData['father_name'])}</td></tr>
    <tr><th>Date of Birth</th><td>{$e($appData['date_of_birth'])}</td><th>Nationality</th><td>{$e($appData['nationality'])}</td></tr>
    <tr><th>Mobile (Verified)</th><td>{$e($appData['mobile_number'])}</td><th>Email (Verified)</th><td>{$e($appData['email_address'])}</td></tr>
    <tr><th>Address</th><td colspan="3">{$e($appData['permanent_address'])}, {$e($appData['district'])}, {$e($appData['state'])} - {$e($appData['pin_code'])}</td></tr>
  </table>
  <div class="section-title">2. Educational & Job Details</div>
  <table>
    <tr><th>10th Board / Year</th><td>{$e($appData['tenth_board'])} ({$e($appData['tenth_passing_year'])})</td><th>10th Marks</th><td>{$e($appData['tenth_marks_obtained'])} / {$e($appData['tenth_total_marks'])}</td></tr>
    <tr><th>12th Board / Year</th><td>{$e($appData['twelfth_board'])} ({$e($appData['twelfth_passing_year'])})</td><th>12th Marks</th><td>{$e($appData['twelfth_marks_obtained'])} / {$e($appData['twelfth_total_marks'])}</td></tr>
    <tr><th>Highest Qualification</th><td>{$e($appData['highest_qualification'])}</td><th>Experience</th><td>{$e($appData['experience_level'])}</td></tr>
    <tr><th>Preferred Location</th><td>{$e($appData['preferred_location'])}</td><th>Computer Skills</th><td>{$e($appData['computer_skills'])}</td></tr>
    {$feeRow}
  </table>
  <div class="section-title">3. Declaration</div>
  <p>I declare that all information provided in this application is true and correct to the best of my knowledge. I understand that incorrect information may affect my application.</p>
  <div class="notice">
    Official recruitment application generated by INDRA AGR TRADING PVT. LTD. portal after verified contact and payment checks.
  </div>
  <div class="footer">
    INDRA AGR TRADING PVT. LTD. — Official Recruitment Application Copy
  </div>
</body>
</html>
HTML;

        $dompdf->loadHtml($html);
        $dompdf->setPaper('A4', 'portrait');
        $dompdf->render();

        $dir = dirname($outputPath);
        if (!is_dir($dir)) {
            mkdir($dir, 0750, true);
        }
        file_put_contents($outputPath, $dompdf->output());

        return $outputPath;
    }

    public static function generatePaymentReceiptPdf(array $receiptData, string $outputPath): string
    {
        $options = new Options();
        $options->set('isRemoteEnabled', false);
        $options->set('defaultFont', 'DejaVu Sans');

        $dompdf = new Dompdf($options);
        $e = static fn(mixed $v): string => htmlspecialchars((string) ($v ?? '—'), ENT_QUOTES, 'UTF-8');
        $amountFormatted = number_format(((int) ($receiptData['amount'] ?? 0)) / 100, 2);

        $html = <<<HTML
<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<style>
  @page { margin: 22mm 18mm 20mm 18mm; }
  body { font-family: 'DejaVu Sans', sans-serif; color: #1B2B22; font-size: 11px; line-height: 1.5; }
  .header { border-bottom: 2px solid #174D32; padding-bottom: 10px; margin-bottom: 16px; }
  .company { font-size: 18px; font-weight: bold; color: #174D32; }
  .subtitle { font-size: 11px; color: #C7A65A; font-weight: bold; margin-top: 2px; }
  .title { font-size: 14px; font-weight: bold; color: #103B27; margin: 12px 0; }
  table { width: 100%; border-collapse: collapse; margin: 12px 0; }
  td, th { border: 1px solid #E2DED2; padding: 7px 10px; text-align: left; }
  th { background: #F6F4EC; color: #103B27; width: 34%; }
  .status-success { color: #174D32; font-weight: bold; }
  .notice { margin-top: 16px; padding: 8px 10px; background: #F6F4EC; border: 1px solid #C7A65A; font-size: 10px; }
  .footer { position: fixed; bottom: -12mm; left: 0; right: 0; font-size: 9px; color: #6B7280; border-top: 1px solid #E2DED2; padding-top: 4px; }
</style>
</head>
<body>
  <div class="header">
    <div class="company">INDRA AGR TRADING PVT. LTD.</div>
    <div class="subtitle">Official Application Fee Payment Receipt</div>
  </div>
  <div class="title">Receipt Number: {$e($receiptData['receipt_number'])}</div>
  <table>
    <tr><th>Candidate Name</th><td>{$e($receiptData['candidate_name'])}</td></tr>
    <tr><th>Application Number</th><td>{$e($receiptData['application_number'])}</td></tr>
    <tr><th>Position Applied For</th><td>{$e($receiptData['job_title'])}</td></tr>
    <tr><th>Payment Gateway</th><td>{$e(strtoupper((string) ($receiptData['gateway_provider'] ?? '')))}</td></tr>
    <tr><th>Payment ID</th><td>{$e($receiptData['gateway_payment_id'])}</td></tr>
    <tr><th>Order ID</th><td>{$e($receiptData['payment_order_id'])}</td></tr>
    <tr><th>UPI Reference (UTR/RRN)</th><td>{$e($receiptData['transaction_reference'] ?? 'Provided by Gateway')}</td></tr>
    <tr><th>Amount Paid</th><td>{$e($receiptData['currency'] ?? 'INR')} {$amountFormatted}</td></tr>
    <tr><th>Payment Date</th><td>{$e($receiptData['payment_date'])}</td></tr>
    <tr><th>Payment Time</th><td>{$e($receiptData['payment_time'])} IST</td></tr>
    <tr><th>Payment Status</th><td class="status-success">{$e(strtoupper((string) ($receiptData['payment_status'] ?? 'SUCCESS')))}</td></tr>
  </table>
  <div class="notice">
    This is a system-generated payment confirmation receipt for your recruitment application fee. This document is an acknowledgement of fee receipt and is not a GST/tax invoice.
  </div>
  <div class="footer">
    INDRA AGR TRADING PVT. LTD. — Connecting Farmers, Growing Businesses.
  </div>
</body>
</html>
HTML;

        $dompdf->loadHtml($html);
        $dompdf->setPaper('A4', 'portrait');
        $dompdf->render();

        $dir = dirname($outputPath);
        if (!is_dir($dir)) {
            mkdir($dir, 0750, true);
        }
        file_put_contents($outputPath, $dompdf->output());

        return $outputPath;
    }
}
